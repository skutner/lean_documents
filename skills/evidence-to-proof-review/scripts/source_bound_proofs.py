"""Retained source-bound proof units and deterministic synthetic perturbations.

Integration configures a ProofEngine with the contract's GenerateFacts and
RenderClaim implementations and a recompute callback, then uses engine.check_proof
or `with using_engine(engine): check_proof(...)`. The callback recomputes the full
ResolvedFacts DAG after replacing the supplied values; it must preserve provenance,
report leaves and registrations. Changed values are SYNTHETIC, not re-extracted
quotes. The frozen contract has no mutation/evaluation protocol, so this explicit
injection avoids depending on another phase's private evaluator or guessing rules.

Pattern categories: compiler diagnostics distinguish generated target decide
failure from declarations/exact assertions/axioms, infrastructure and timeout;
provenance interning distinguishes identical byte selections from repeated tokens,
wrong rows, different hashes/types/units; dependency traversal distinguishes source,
report, rule, field, unit, scope and list edges. No legacy/default route is changed.
Every attempt binds input bytes, generated bytes, callbacks, engine/contract code,
Lean executable and sandbox command. Markdown journals retain units and raw output;
resumption reclassifies hash-checked output rather than trusting a saved verdict.
The coordinator must review the supplied no-network sandbox; lexical inspection
and the bwrap argument sanity check are not substitutes for that review.
"""
from __future__ import annotations

import ast
from contextlib import contextmanager
