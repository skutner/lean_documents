_ENGINE: ContextVar['ProofEngine | None'] = ContextVar('source_bound_engine', default=None)
_ALLOWED_AXIOMS = {'propext', 'Classical.choice', 'Quot.sound'}


def _hash(data: str | bytes) -> str:
    return sha256(data.encode('utf-8') if isinstance(data, str) else data).hexdigest()


def mutations(type_: c.TypeSpec, value: c.Value,
              domains: tuple[c.EnumDomain, ...] = ()) -> tuple[c.Value, ...]:
    """Valid deterministic alternatives only; generated ints use money's deltas."""
    candidates = []
    if isinstance(type_, c.ListType):
        if value:
            candidates = [value[1:], (value[0],) + value]
    elif isinstance(type_, c.ScalarType):
        kind = type_.kind
        if kind == 'nat':
            candidates = [0, value + 1]
        elif kind in {'money', 'int'}:
            candidates = [value - 1, value + 1, -value]
        elif kind == 'date':
            for delta in (-1, 1):
                try:
                    candidates.append(value + timedelta(days=delta))
                except OverflowError:
                    pass
        elif kind == 'bool':
            candidates = [not value]
        elif kind == 'enum':
            labels = sorted(next((d.labels for d in domains if d.id == type_.parameter), ()))
            if value not in labels:
                raise c.ContractError('Mutation enum value has no registered domain label')
            if len(labels) > 1:
                candidates = [labels[(labels.index(value) + 1) % len(labels)]]
        elif kind == 'ratio':
            candidates = [Fraction(value.numerator - 1, value.denominator),
                          Fraction(value.numerator + 1, value.denominator)]
    result = []
    for candidate in candidates:
        if candidate != value and candidate not in result:
            result.append(candidate)
    return tuple(result)


def _edges(node):
    if isinstance(node, c.FactRecord):
        return (node.unit_source,) if node.unit_source else ()
    if isinstance(node, c.DerivedRecord):
        return (node.inputs + tuple(r for _, r in node.fields) + node.scope
                + ((node.rule,) if node.rule else ()))
    if isinstance(node, c.RuleRegistration):
        return node.dependencies
    return ()


def dependency_groups(rendered: c.RenderedClaim, facts: c.ResolvedFacts,
                      rules: tuple[c.RuleRegistration, ...]) -> tuple[tuple[str, ...], ...]:
    """Walk actual DAG, not cached leaves; intern exact source byte selections.

    List nodes receive structural mutations as well as their scalar leaves.
    Mixed/report lists are never mutated because that would mutate report values.
    Unbound provenance is an error, never retrospectively called source evidence.
    """
    c.validate_dag(facts.document, rules)
    nodes = {n.id: n for n in (*facts.document.facts, *facts.document.derived,
                              *rules, *facts.document.scopes)}
    values = {v.id: v for v in facts.values}
    roots = rendered.dependencies + rendered.claim.rules + rendered.claim.scope
    roots += tuple(s.value for s in rendered.claim.slots if isinstance(s.value, c.Reference))
    pending, seen, selected = [r.id for r in roots], set(), set()
    while pending:
        ident = pending.pop()
        if ident in seen:
            continue
        if ident not in nodes:
            raise c.ContractError(f'Unknown target dependency: {ident}')
        seen.add(ident)
        node = nodes[ident]
        if isinstance(node, c.FactRecord) and node.origin == c.Origin.SOURCE:
            selected.add(ident)
        if isinstance(node, c.DerivedRecord) and isinstance(node.type, c.ListType):
            if not c.report_origin_leaves(c.Reference(ident), facts, rules):
                selected.add(ident)
        pending.extend(r.id for r in _edges(node))
    groups = {}
    # Intern all aliases of an encountered selection, including aliases reached
    # through a different target edge, to avoid contradictory synthetic copies.
    for ident in sorted(nodes):
        node = nodes[ident]
        if isinstance(node, c.FactRecord) and node.origin == c.Origin.SOURCE:
            value = values[ident]
            if not value.provenance:
                if ident in selected:
                    raise c.ContractError(f'Missing source provenance: {ident}')
                continue
            key = (node.type, tuple((p.original_path, p.original_sha256,
                p.projection_sha256, p.passage_sha256, p.evidence.source_path,
                p.evidence.anchor, p.evidence.quote_start + p.selection.start,
                p.evidence.quote_start + p.selection.end) for p in value.provenance))
            groups.setdefault(key, []).append(ident)
    result = []
    for ids in groups.values():
        if selected.intersection(ids):
            if any(values[i].value != values[ids[0]].value for i in ids):
                raise c.ContractError('Identical provenance selections disagree in value')
            result.append(tuple(ids))
    result.extend((i,) for i in sorted(selected) if isinstance(nodes[i], c.DerivedRecord))
    return tuple(sorted(result))


@dataclass(frozen=True)
class ProcessResult:
    outcome: str  # checked, target_failed, inconclusive
    log: str
    unit: str
    elapsed: float


def _classify(code: int | None, output: str, unit: Path, target_line: int,
              theorem: str) -> str:
    if code == 0:
        marker = re.escape(theorem)
        match = re.search(r"'" + marker + r"' depends on axioms:\s*\[([^\]]*)\]", output, re.S)
        empty = re.search(r"'" + marker + r"' does not depend on any axioms", output)
        if match:
            axioms = {a.strip() for a in match.group(1).split(',') if a.strip()}
            if not axioms - _ALLOWED_AXIOMS:
                return 'checked'
        elif empty:
            return 'checked'
        return 'inconclusive'
    # Only the generated `by decide` failure at the selected theorem counts.
    # All other diagnostics (including the later assertion's unknown theorem)
    # are unrelated/infrastructure errors. A second kernel check is still needed.
    errors = re.findall(r'^.*?:(\d+):(\d+): error(?:\([^\n)]*\))?:([^\n]*)', output, re.M)
    if code == 1 and errors and all(int(line) == target_line for line, _, _ in errors):
        if re.search(r"(?:Tactic `decide`|tactic 'decide') proved that the proposition", output) and 'is false' in output:
            return 'target_failed'
    return 'inconclusive'


def _safe_file(root: Path, relative: str) -> Path:
    path = root / relative
    if Path(relative).is_absolute() or '..' in Path(relative).parts or not path.resolve().is_relative_to(root.resolve()):
        raise c.ContractError(f'Artifact path escapes workspace: {relative}')
    return path


def _write_once(path: Path, content: str) -> None:
    if path.is_symlink():
        raise c.ContractError('Symlink in retained attempt artifacts')
    if path.exists():
        if path.read_text(encoding='utf-8') != content:
            raise c.ContractError(f'Stale or tampered attempt artifact: {path.name}')
    else:
        path.write_text(content, encoding='utf-8')


def _callback_hash(callback) -> str:
    try:
        source = inspect.getsource(callback)
    except (OSError, TypeError):
        raise c.ContractError('Regeneration callbacks must have inspectable source')
    module = inspect.getmodule(callback)
    file = getattr(module, '__file__', None)
    return _hash(source + (_hash(Path(file).read_bytes()) if file else ''))


class ProofEngine:
    """Explicit protocol adapters, with no import or private API assumptions.

    recompute(facts, replacements, rules) returns a fresh ResolvedFacts with every
    dependent value reevaluated (including rule/filter applicability). Replacements
    name scalar selection aliases or a structural list node. Do not re-extract or
    claim quote agreement for synthetic values. Engine checks preserved records,
    provenance, unchanged report values and exact requested replacements.
    """
    def __init__(self, generate_facts: c.GenerateFacts, render_claim: c.RenderClaim,
                 recompute: c.RecomputeFacts, *, aggregate_claims=None):
        self.generate_facts = generate_facts
        self.render_claim = render_claim
        self.recompute = recompute
        # Optional deterministic batch renderer for the workspace Claims.lean.
        # Compilation still uses _unit's single selected target and axiom check.
        self.aggregate_claims = aggregate_claims

    def _render(self, original, facts, rules):
        rendered = self.render_claim(original.claim, facts, rules, original.relation)
        if rendered.claim != original.claim or rendered.relation != original.relation:
            raise c.ContractError('Regeneration changed claim registration or relation')
        return rendered

    def _files(self, facts, rules, rendered, authored):
        files = self.generate_facts(facts, rules) + rendered.files + authored
        paths = [f.path for f in files]
        if len(set(paths)) != len(paths):
            raise c.ContractError('Duplicate generated/authored artifact path')
        modules = {f.path: f.content for f in files if f.path.endswith('.lean')}
        expected = {'models/' + m.replace('.', '/') + '.lean' for m in c.MODULE_ORDER}
        if modules.keys() != expected:
            raise c.ContractError('Generated module closure does not match MODULE_ORDER')
        return files

    def _unit(self, files, rendered, *, negate=False):
        modules = {f.path: f.content for f in files}
        parts = []
        for module in c.MODULE_ORDER:
            if module == 'SourceBound.Claims':
                continue
            text = modules['models/' + module.replace('.', '/') + '.lean']
            imports = tuple(re.findall(r'^\s*import\s+([\w.]+)\s*$', audit.lean_code(text), re.M))
            if imports != c.MODULE_IMPORTS[module]:
                raise c.ContractError(f'Unexpected generated imports in {module}')
            # Each module is a self-contained namespace scope. Only fixed imports
            # are removed; no olean is loaded from agent/workspace search paths.
            text = re.sub(r'^\s*import\s+[\w.]+\s*$', '', text, flags=re.M)
            parts.append(f'-- Module: {module}\n{text.rstrip()}\n')
        target = rendered.target
        if not target or '\n' in target or '\r' in target:
            raise c.ContractError('Target must be one generated proposition')
        code = audit.lean_code(target, reject_comments=True, mask_strings=False)
        if re.search(r'\b(theorem|lemma|def|example|import|axiom|by|where|end|namespace|section|set_option|attribute|elab|macro|initialize)\b|:=|[;`#"\']', code):
            raise c.ContractError('Command or literal in generated target')
        target = f'¬ ({target})' if negate else target
        theorem = c.lean_claim_name(rendered.claim.id)
        prefix = '\n'.join(parts)
        line = prefix.count('\n') + 1
        # A failed decide leaves a sorry placeholder in Lean; the following exact
        # assertion usually still elaborates. Its diagnostics never count as proof.
        content = (prefix + f'theorem {theorem} : ({target}) := by decide\n'
                   + f'example : ({target}) := {theorem}\n'
                   + f'#print axioms {theorem}\n')
        return content, line, theorem

    def check_proof(self, workspace: Path, rendered: c.RenderedClaim, facts: c.ResolvedFacts,
                    rules: tuple[c.RuleRegistration, ...], authored: tuple[c.GeneratedFile, ...],
                    *, budget: c.GuardBudget, attempt_directory: Path,
                    sandbox_command: tuple[str, ...]) -> c.GuardResult:
        from source_bound_guards import detect_transcription, generated_aliases, inspect_rules
        root = Path(workspace).resolve()
        attempt = Path(attempt_directory).resolve()
        if not attempt.is_relative_to(root / 'tmp'):
            raise c.ContractError('Attempt directory must be under workspace/tmp')
        attempt.mkdir(parents=True, exist_ok=True)
        if any(not isinstance(n, int) or isinstance(n, bool) or n < 0 for n in
               (budget.mutants, budget.process_seconds, budget.theorem_seconds)):
            raise c.ContractError('Guard budgets must be nonnegative integers')
        if budget.mutants > 64 or budget.process_seconds > 10 or budget.theorem_seconds > 120:
            raise c.ContractError('Budget exceeds hard caps: 64 mutants, 10 seconds/process, 120 seconds/theorem')
        flags, logs, leaves = set(), [], []
        supported = rendered.target is not None and not rendered.not_formalized_reason
        if not supported:
            return c.GuardResult(frozenset(), False, c.resolve_status(supported=False,
                baseline_checked=False, flags=frozenset(), relation=rendered.relation), (), (), None, ())
        c.build_lean_bindings(facts)
        regenerated = self._render(rendered, facts, rules)
        if regenerated != rendered:
            raise c.ContractError('Claim regeneration mismatch')
        if len(authored) != 1 or authored[0].path != 'models/Rules.lean':
            raise c.ContractError('Only models/Rules.lean is authored in this profile')
        for artifact in authored:
            path = _safe_file(root, artifact.path)
            if not path.is_file() or path.read_text(encoding='utf-8') != artifact.content:
                raise c.ContractError('Authored module mismatch')
        aliases = inspect_rules(root / 'models/Rules.lean', facts, rules)
        files = self._files(facts, rules, regenerated, authored)
        disk_files = files
        if self.aggregate_claims is not None:
            aggregate = self.aggregate_claims(facts, rules)
            if len(aggregate) != 1 or aggregate[0].path != 'models/SourceBound/Claims.lean':
                raise c.ContractError('Expected one aggregate Claims.lean artifact')
            disk_files = tuple(f for f in files if f.path != aggregate[0].path) + aggregate
        for artifact in disk_files:
            path = _safe_file(root, artifact.path)
            if not path.is_file() or path.read_bytes() != artifact.content.encode('utf-8'):
                raise c.ContractError(f'Deterministic regeneration mismatch: {artifact.path}')
        aliases.update(generated_aliases(facts, files))
        flags.update(detect_transcription(rendered.target, aliases))
        # Input hashes also cover source projections/manifests and non-Lean outputs.
        input_hashes = []
        for directory in ('input', 'source-bound', 'models'):
            for path in sorted((root / directory).rglob('*')):
                if path.is_file():
                    _safe_file(root, path.relative_to(root).as_posix())
                    input_hashes.append((path.relative_to(root).as_posix(), _hash(path.read_bytes())))
        executable = Path(sandbox_command[-1]) if sandbox_command else None
        executable_hash = _hash(executable.read_bytes()) if executable and executable.is_file() else None
        identity = _hash(repr((c.PROFILE_VERSION, c.PARSER_VERSION, c.CATALOGUE_VERSION,
            facts, rendered, rules, authored, files, input_hashes, sandbox_command, executable_hash,
            _hash(Path(__file__).read_bytes()), _hash(Path(c.__file__).read_bytes()),
            _hash(Path(inspect.getfile(detect_transcription)).read_bytes()),
            _callback_hash(self.generate_facts), _callback_hash(self.render_claim),
            _callback_hash(self.recompute),
            _callback_hash(self.aggregate_claims) if self.aggregate_claims else None)))
        _write_once(attempt / 'identity.md', '# Hash-bound proof attempt\n\nSHA-256: ' + identity + '\n')
        unit, target_line, theorem = self._unit(files, rendered)
        mapping = tuple((module, str(attempt / 'baseline.lean')) for module in c.MODULE_ORDER)
        _write_once(attempt / 'modules.md', '# Module-to-unit map\n\n' + '\n'.join(
            f'- {module}: baseline.lean' for module in c.MODULE_ORDER) + '\n')
        if c.GuardFlag.ROOT_TRUE in flags:
            return self._result(flags, False, rendered, leaves, logs, None, mapping)
        sandbox_ok = bool(sandbox_command and Path(sandbox_command[0]).name == 'bwrap'
            and ('--unshare-net' in sandbox_command or '--unshare-all' in sandbox_command)
            and '--share-net' not in sandbox_command)
        if not sandbox_ok:
            flags.update((c.GuardFlag.INCOMPLETE, c.GuardFlag.BASELINE_FAILED))
            note = attempt / 'sandbox.md'
            _write_once(note, '# Execution blocked\n\nA reviewed no-network Bubblewrap command is required.\n')
            logs.append(str(note))
            return self._result(flags, False, rendered, leaves, logs, None, mapping)
        started = time.monotonic()
        spent = 0.0
        # Each reserved process slot is immutable, including interrupted slots.
        # Resumption never silently obtains extra processes or resets elapsed cost.
        for meta in attempt.glob('*.result.md'):
            record = self._read_result(meta)
            spent += record['elapsed']
        for pending in attempt.glob('*.pending.md'):
            if not pending.with_name(pending.name.replace('.pending.md', '.result.md')).exists():
                reservation = self._read_pending(pending)
                spent += reservation['reserved_seconds']
        remaining = lambda: budget.theorem_seconds - spent - (time.monotonic() - started)

        def execution_log(name, source, command, code, output, elapsed):
            title = '# Synthetic mutation execution\n\n' if name != 'baseline' else '# Baseline execution\n\n'
            return (title + f'Unit SHA-256: {_hash(source)}\n\nCommand: {shlex.join(command)}\n\n'
                    + f'Exit code: {code}\n\nElapsed: {elapsed!r}\n\nOutput:\n\n' + output)

        def run(name, source, line):
            unit_path = attempt / (name + '.lean')
            log_path = attempt / (name + '.log.md')
            meta_path = attempt / (name + '.result.md')
            _write_once(unit_path, source)
            command = (*sandbox_command, str(unit_path))
            if meta_path.exists():
                record = self._read_result(meta_path)
                if record['unit_hash'] != _hash(source) or not log_path.exists() or record['log_hash'] != _hash(log_path.read_bytes()):
                    raise c.ContractError('Stale or tampered process evidence')
                expected_log = execution_log(name, source, command, record['code'], record['output'], record['elapsed'])
                if expected_log != log_path.read_text(encoding='utf-8'):
                    raise c.ContractError('Process metadata disagrees with retained compiler log')
                outcome = _classify(record['code'], record['output'], unit_path, line, theorem)
                return ProcessResult(outcome, str(log_path), str(unit_path), record['elapsed'])
            pending = attempt / (name + '.pending.md')
            if pending.exists():
                reservation = self._read_pending(pending)
                if reservation['unit_hash'] != _hash(source):
                    raise c.ContractError('Stale interrupted process unit')
                return ProcessResult('inconclusive', str(pending), str(unit_path), 0)
            timeout = min(budget.process_seconds, remaining())
            if timeout <= 0:
                return None
            _write_once(pending, repr(dict(unit_hash=_hash(source), reserved_seconds=timeout)) + '\n')
            env = {'PATH': os.environ.get('PATH', '/usr/bin:/bin'), 'HOME': str(attempt),
                   'LEAN_PATH': '', 'LANG': 'C.UTF-8'}
            command = (*sandbox_command, str(unit_path))
            begin = time.monotonic()
            code, output = None, ''
            try:
                result = subprocess.run(command, cwd=attempt, env=env, capture_output=True,
                                        text=True, timeout=timeout, check=False)
                code, output = result.returncode, result.stdout + '\n' + result.stderr
            except subprocess.TimeoutExpired as exc:
                def decode(s):
                    return s.decode('utf-8', errors='replace') if isinstance(s, bytes) else s or ''
                output = 'TIMEOUT\n' + decode(exc.stdout) + '\n' + decode(exc.stderr)
            except OSError as exc:
                output = 'INFRASTRUCTURE ERROR\n' + str(exc)
            elapsed = time.monotonic() - begin
            log = execution_log(name, source, command, code, output, elapsed)
            _write_once(log_path, log)
            record = dict(unit_hash=_hash(source), log_hash=_hash(log), code=code,
                          output=output, elapsed=elapsed)
            _write_once(meta_path, '# Process evidence\n\n' + repr(record) + '\n')
            return ProcessResult(_classify(code, output, unit_path, line, theorem),
                                 str(log_path), str(unit_path), elapsed)

        baseline = run('baseline', unit, target_line)
        checked = baseline is not None and baseline.outcome == 'checked'
        if baseline:
            logs.append(baseline.log)
        if not checked:
            flags.add(c.GuardFlag.BASELINE_FAILED)
            if baseline is None or baseline.outcome == 'inconclusive':
                flags.add(c.GuardFlag.INCOMPLETE)
            return self._result(flags, False, rendered, leaves, logs, None, mapping)
        groups = dependency_groups(rendered, facts, rules)
        values = {v.id: v for v in facts.values}
        index, confirmed_total = 0, 0
        if not groups:
            flags.add(c.GuardFlag.INCOMPLETE)
        for ids in groups:
            value = values[ids[0]]
            alternatives = mutations(value.type, value.value, facts.document.enum_domains)
            attempted, confirmed, inconclusive, leaf_logs = 0, 0, 0, []
            if not alternatives:
                flags.add(c.GuardFlag.INCOMPLETE)
            for replacement in alternatives:
                index += 1
                if index > budget.mutants or remaining() <= 0:
                    flags.add(c.GuardFlag.INCOMPLETE)
                    continue
                changes = {i: replacement for i in ids}
                try:
                    changed = self.recompute(facts, changes, rules)
                except c.ContractError as exc:
                    # A valid scalar perturbation may invalidate a downstream
                    # denominator or rule domain. Retain this synthetic failure
                    # and continue; never count it as a failed selected target.
                    attempted += 1
                    inconclusive += 1
                    flags.add(c.GuardFlag.INCOMPLETE)
                    note = attempt / f'mutant-{index:03d}.recompute.md'
                    _write_once(note, '# Synthetic mutation; recomputation inconclusive\n\n' + str(exc) + '\n')
                    leaf_logs.append(str(note))
                    continue
                self._validate_mutation(facts, changed, changes)
                mutant = self._render(rendered, changed, rules)
                attempted += 1
                if mutant.not_formalized_reason or mutant.target is None:
                    inconclusive += 1
                    flags.add(c.GuardFlag.INCOMPLETE)
                    note = attempt / f'mutant-{index:03d}.applicability.md'
                    _write_once(note, '# Synthetic mutation; applicability not established\n\n' +
                                (mutant.not_formalized_reason or 'No target') + '\n')
                    leaf_logs.append(str(note))
                    continue
                if mutant.target != rendered.target or mutant.proposition != rendered.proposition:
                    raise c.ContractError('Mutation changed target shape rather than its facts')
                mutant_files = self._files(changed, rules, mutant, authored)
                source, line, _ = self._unit(mutant_files, mutant)
                result = run(f'mutant-{index:03d}', source, line)
                if result is None:
                    attempted -= 1
                    flags.add(c.GuardFlag.INCOMPLETE)
                    continue
                leaf_logs.append(result.log)
                if result.outcome == 'target_failed':
                    neg_source, neg_line, _ = self._unit(mutant_files, mutant, negate=True)
                    negation = run(f'negation-{index:03d}', neg_source, neg_line)
                    if negation:
                        leaf_logs.append(negation.log)
                    if negation and negation.outcome == 'checked':
                        confirmed += 1
                    else:
                        inconclusive += 1
                        flags.add(c.GuardFlag.INCOMPLETE)
                elif result.outcome == 'inconclusive':
                    inconclusive += 1
                    flags.add(c.GuardFlag.INCOMPLETE)
            confirmed_total += confirmed
            leaves.append(c.LeafSensitivity(ids, len(alternatives), attempted, confirmed,
                                             inconclusive, not alternatives, tuple(leaf_logs)))
            logs.extend(leaf_logs)
        if not confirmed_total and c.GuardFlag.INCOMPLETE not in flags:
            flags.add(c.GuardFlag.NO_TESTED_SOURCE_SENSITIVITY)
        return self._result(flags, True, rendered, leaves, logs, baseline.unit, mapping)

    @staticmethod
    def _read_pending(path):
        try:
            record = ast.literal_eval(path.read_text(encoding='utf-8'))
            if (not isinstance(record, dict) or set(record) != {'unit_hash', 'reserved_seconds'}
                    or not isinstance(record['reserved_seconds'], (int, float))
                    or not 0 < record['reserved_seconds'] <= 10):
                raise ValueError('Invalid process reservation')
            return record
        except (SyntaxError, ValueError) as exc:
            raise c.ContractError('Malformed process reservation') from exc

    @staticmethod
    def _read_result(path):
        try:
            record = ast.literal_eval(path.read_text(encoding='utf-8').split('\n\n', 1)[1])
            if not isinstance(record, dict) or set(record) != {'unit_hash', 'log_hash', 'code', 'output', 'elapsed'}:
                raise ValueError('Unexpected evidence schema')
            if not isinstance(record['elapsed'], (int, float)) or not 0 <= record['elapsed'] <= 60:
                raise ValueError('Invalid elapsed cost')
            return record
        except (SyntaxError, ValueError, IndexError) as exc:
            raise c.ContractError('Malformed process evidence') from exc

    @staticmethod
    def _validate_mutation(original, changed, replacements):
        if original.document != changed.document:
            raise c.ContractError('Synthetic regeneration changed documentary records')
        before, after = {v.id: v for v in original.values}, {v.id: v for v in changed.values}
        if before.keys() != after.keys():
            raise c.ContractError('Synthetic regeneration changed value identities')
        records = original.document.records()
        for ident, value in after.items():
            old = before[ident]
            if replace(value, value=old.value) != old:
                raise c.ContractError('Synthetic regeneration changed provenance/type/dependencies')
            if ident in replacements:
                if value.value != replacements[ident]:
                    raise c.ContractError('Synthetic replacement was not applied')
            elif isinstance(records[ident], c.FactRecord) and value.value != old.value:
                node = records[ident]
                # A quoted source cell can depend on a changed unit header.
                # Report-origin facts remain fixed even through that edge.
                header = node.unit_source
                if (node.origin != c.Origin.SOURCE or not header or
                        before[header.id].value == after[header.id].value):
                    raise c.ContractError('Mutation changed an unrelated source or report fact')

    @staticmethod
    def _result(flags, checked, rendered, leaves, logs, reference, mapping):
        flags = frozenset(flags)
        decision = c.resolve_status(supported=True, baseline_checked=checked, flags=flags,
                                    relation=rendered.relation)
        summary = ('# Source-bound guard result\n\n'
                   + f'Status: {decision.status}\n\nBaseline checked: {checked}\n\n'
                   + 'Flags: ' + ', '.join(sorted(flags)) + '\n\n')
        if c.GuardFlag.NO_TESTED_SOURCE_SENSITIVITY in flags:
            summary += ('not depending on sources under these perturbations\n\n'
                        'This does not prove mathematical independence.\n\n')
        summary += '| Source selections | Scheduled | Attempted | Confirmed | Inconclusive | Untestable |\n'
        summary += '| --- | ---: | ---: | ---: | ---: | --- |\n'
        for leaf in leaves:
            summary += (f'| {", ".join(leaf.leaf_ids)} | {leaf.scheduled} | {leaf.attempted} | '
                        f'{leaf.confirmed} | {leaf.inconclusive} | {leaf.untestable} |\n')
        if mapping:
            path = Path(mapping[0][1]).parent / ('result-' + _hash(summary)[:16] + '.md')
            _write_once(path, summary)
            logs = [*logs, str(path)]
        return c.GuardResult(flags, checked, decision, tuple(leaves), tuple(logs),
                             reference if decision.reference_kind else None, mapping)


@contextmanager
def using_engine(engine: ProofEngine):
    """Task-local configuration; restores prior engine even after interruption."""
    token = _ENGINE.set(engine)
    try:
        yield engine
    finally:
        _ENGINE.reset(token)


def check_proof(workspace: Path, rendered: c.RenderedClaim, facts: c.ResolvedFacts,
                rules: tuple[c.RuleRegistration, ...], authored: tuple[c.GeneratedFile, ...],
                *, budget: c.GuardBudget, attempt_directory: Path,
                sandbox_command: tuple[str, ...]) -> c.GuardResult:
    """Frozen CheckProof signature; use using_engine to supply protocol adapters."""
    engine = _ENGINE.get()
    if engine is None:
        raise c.ContractError('Configure source-bound ProofEngine with using_engine first')
    return engine.check_proof(workspace, rendered, facts, rules, authored, budget=budget,
                             attempt_directory=attempt_directory, sandbox_command=sandbox_command)
