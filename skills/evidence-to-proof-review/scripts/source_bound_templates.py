"""Generator-owned source-bound claim catalogue; no authored Lean target input.

``render_claim`` implements the frozen RenderClaim protocol. ``generate_claims``
renders a batch again from records and returns its single Claims.lean artifact;
it never accepts free targets or trusts a caller-constructed RenderedClaim.
Both functions are pure: the integration layer writes GeneratedFile content.

English labels default to identifiers with underscores replaced by spaces.
Callers may supply display-only ``labels`` keyed by reference/field ID. Labels
never enter Lean. The report anchor/text remains unchanged. English describes Q
(including report polarity), and never changes with the proof relation.

Nonempty/positive applicability is checked before negation; the proposition
contains only the substantive predicate. Rules is imported transitively through
Derived, following MODULE_IMPORTS exactly. Lean core suffices for this catalogue,
so no additional support module or change to Types.lean is required.
"""
from __future__ import annotations

from fractions import Fraction
from typing import Mapping

from source_bound_contract import (
    CATALOGUE_VERSION, MODULE_IMPORTS, MODULE_ORDER, SHAPES, ClaimRecord,
    ContractError, DerivedRecord, FactRecord, GeneratedFile, ListType, Origin,
    Polarity, ProofRelation, RecordType, Reference, RenderedClaim, ResolvedFacts,
    RuleRegistration, ScalarType, SlotKind, TypeSpec, claim_rule_input_reason,
    lean_claim_name, lean_comparison_operands, lean_type_binding,
    report_origin_leaves, validate_dag,
)


_PHRASES = {'=': 'equal to', '≠': 'not equal to', '<': 'less than',
            '≤': 'less than or equal to', '>': 'greater than',
            '≥': 'greater than or equal to'}
_NAT, _BOOL, _DATE, _RATIO = (ScalarType(k) for k in ('nat', 'bool', 'date', 'ratio'))


class _NotFormalized(Exception):
    pass


def _require(condition: bool, reason: str) -> None:
    if not condition:
        raise _NotFormalized(reason)


def _integer_unit(type_: TypeSpec) -> str | None:
    if isinstance(type_, ScalarType):
        if type_.kind in ('nat', 'int'):
            return 'integer'
        if type_.kind == 'money':
            return type_.parameter
    return None


def _ordered(type_: TypeSpec) -> bool:
    return _integer_unit(type_) is not None or type_ in (_DATE, _RATIO)


def _closure(facts: ResolvedFacts, rules: tuple[RuleRegistration, ...],
             roots: tuple[Reference, ...]) -> tuple[object, ...]:
    """Traverse actual edges, not cached source/report leaf summaries."""
    nodes = {n.id: n for n in (*facts.document.facts, *facts.document.derived,
                              *rules, *facts.document.scopes)}
    seen, result, pending = set(), [], [r.id for r in roots]
    while pending:
        ident = pending.pop()
        if ident in seen:
            continue
        _require(ident in nodes, f'Unresolved dependency: {ident}')
        seen.add(ident)
        node = nodes[ident]
        result.append(node)
        if isinstance(node, FactRecord):
            edges = (node.unit_source,) if node.unit_source else ()
        elif isinstance(node, DerivedRecord):
            edges = node.inputs + tuple(r for _, r in node.fields) + node.scope
            edges += (node.rule,) if node.rule else ()
        elif isinstance(node, RuleRegistration):
            edges = node.dependencies
        else:
            edges = ()
        pending.extend(r.id for r in edges)
    return tuple(result)


def _claims_file(rendered: tuple[RenderedClaim, ...]) -> tuple[GeneratedFile, ...]:
    supported = sorted((r for r in rendered if r.target is not None), key=lambda r: r.claim.id)
    if not supported:
        return ()
    module = MODULE_ORDER[-1]
    header = f'-- Generated by {CATALOGUE_VERSION}; do not edit.\n'
    header += ''.join(f'import {name}\n' for name in MODULE_IMPORTS[module]) + '\n'
    declarations = '\n\n'.join(
        f'theorem {lean_claim_name(r.claim.id)} :\n    {r.target} := by decide'
        for r in supported)
    return (GeneratedFile('models/' + module.replace('.', '/') + '.lean',
                          header + declarations + '\n'),)


def render_claim(claim: ClaimRecord, facts: ResolvedFacts,
                 rules: tuple[RuleRegistration, ...], relation: ProofRelation, *,
                 labels: Mapping[str, str] | None = None) -> RenderedClaim:
    """Render Q, its selected proof target and fixed English, or no theorem.

    The four positional arguments are exactly RenderClaim's protocol. Invalid
    reference syntax/categories raise ContractError. Unsupported shapes, missing
    inputs, incompatible types, source independence and applicability failures
    return not_formalized_reason with no proposition, target or files. This does
    not certify extraction, rule correspondence or a successful Lean proof.
    """
    lean_claim_name(claim.id)  # Contract identifier validation, not interpolation.
    if claim.polarity not in tuple(Polarity) or relation not in tuple(ProofRelation):
        raise ContractError('Unsupported polarity or proof relation')
    spec = SHAPES.get(claim.shape)
    slots = {s.name: s for s in claim.slots}
    if len(slots) != len(claim.slots):
        raise ContractError('Duplicate claim slot')
    for slot in claim.slots:
        lean_claim_name(slot.name)
        if slot.kind in (SlotKind.VALUE, SlotKind.RULE):
            if not isinstance(slot.value, Reference):
                raise ContractError('Value/rule slots require typed references')
            lean_claim_name(slot.value.id)
        elif slot.kind == SlotKind.FIELD:
            if not isinstance(slot.value, str):
                raise ContractError('Field slot requires an identifier')
            lean_claim_name(slot.value)
        elif slot.kind != SlotKind.CHOICE:
            raise ContractError('Unknown slot category')
    for ref in claim.rules + claim.scope:
        lean_claim_name(ref.id)
    if spec:
        if slots.keys() != {s.name for s in spec.slots}:
            raise ContractError('Unknown or missing shape slots')
        for s in spec.slots:
            if slots[s.name].kind != s.kind:
                raise ContractError(f'Wrong slot category: {s.name}')
            if s.choices and slots[s.name].value not in s.choices:
                raise ContractError(f'Unsupported catalogue choice: {s.name}')
    used = tuple(s.value for s in claim.slots if isinstance(s.value, Reference))
    dependencies = tuple(Reference(i) for i in sorted({r.id for r in used + claim.rules + claim.scope}))

    def blocked(reason: str) -> RenderedClaim:
        if not reason.startswith('not formalized:'):
            reason = 'not formalized: ' + reason
        return RenderedClaim(claim, relation, None, None, '', dependencies, (), reason)

    try:
        _require(spec is not None and claim.version == spec.version, 'Unsupported shape/version')
        _require(claim.not_formalized_reason is None, claim.not_formalized_reason or '')
        records = facts.document.records()
        values = {v.id: v for v in facts.values}
        registered = {r.id: r for r in rules}
        for slot in claim.slots:
            if slot.kind == SlotKind.VALUE:
                _require(slot.value.id in records and slot.value.id in values,
                         f'Unresolved value slot {slot.name}: {slot.value.id}')
            elif slot.kind == SlotKind.RULE:
                _require(slot.value.id in registered, f'Unresolved rule slot {slot.name}: {slot.value.id}')
                if slot.value not in claim.rules:
                    raise ContractError('Rule slots must be listed in Rules')
        for ref in claim.rules:
            _require(ref.id in registered, f'Unregistered rule: {ref.id}')
        for ref in claim.scope:
            _require(ref.id in records or ref.id in {s.id for s in facts.document.scopes},
                     f'Unresolved scope reference: {ref.id}')
        _require(records.keys() == values.keys(), 'Incomplete resolved facts')
        validate_dag(facts.document, rules)
        bindings = facts.bindings
        reason = claim_rule_input_reason(claim, facts, rules)
        if reason:
            return blocked(reason)
        closure = _closure(facts, rules, used)
        _require(any(isinstance(n, FactRecord) and n.origin == Origin.SOURCE for n in closure),
                 'No independent source dependency')
        for node in closure:
            if isinstance(node, RuleRegistration):
                taint = report_origin_leaves(Reference(node.id), facts, rules)
                _require(not taint, f'Rule {node.id} has report-origin leaves: {", ".join(taint)}')

        def value(key):
            return values[slots[key].value.id]

        def name(key):
            return bindings.values[slots[key].value.id].name

        def label(key):
            ref = slots[key].value
            ident = ref.id if isinstance(ref, Reference) else ref
            return (labels or {}).get(ident, ident.replace('_', ' '))

        def type_binding(type_):
            return bindings.types.get(type_) or lean_type_binding(type_, facts.document.enum_domains)

        def integer(key):
            binding = type_binding(value(key).type)
            _require(binding.integer_projection is not None, f'No integer projection: {key}')
            return binding.integer_projection.format(value=name(key))

        def compatible(*types):
            units = tuple(_integer_unit(t) for t in types)
            _require(None not in units and len(set(units)) == 1, 'Incompatible integer units')

        def compare(type_, left, right, operator):
            _require(_ordered(type_), 'Unsupported ordered type')
            a, b = lean_comparison_operands(type_binding(type_), left, right)
            return f'({a}) {operator} ({b})'

        def predicate(key, element, result=None):
            rule = registered[slots[key].value.id]
            _require(len(rule.parameters) == 1 and rule.parameters[0][1] == element,
                     f'Rule {rule.id} must take exactly one list element')
            if result is not None:
                _require(rule.result_type == result, f'Wrong result type for rule {rule.id}')
            return rule, 'Rules.' + rule.id  # Fixed RuleRegistration ABI.

        shape = claim.shape
        op = slots['cmp'].value if 'cmp' in slots else None
        phrase = _PHRASES.get(op)
        if shape == 'equal':
            _require(value('a').type == value('b').type, 'Equality requires identical types')
            p = f'{name("a")} = {name("b")}'
            english = f'{label("a")} equals {label("b")}.'
        elif shape == 'sum':
            xs = value('xs').type
            _require(isinstance(xs, ListType), 'sum requires a list')
            compatible(xs.element, value('v').type)
            projection = type_binding(xs.element).integer_projection.format(value='item')
            p = f'({name("xs")}.map (fun item => {projection})).sum = {integer("v")}'
            english = f'The sum of {label("xs")} equals {label("v")}.'
        elif shape == 'compare':
            _require(value('a').type == value('b').type, 'Comparison requires identical types/units')
            if value('a').type == _RATIO:
                for key in ('a', 'b'):
                    _require(isinstance(value(key).value, Fraction) and value(key).value.denominator > 0,
                             'Applicability requires positive ratio denominators')
            p = compare(value('a').type, name('a'), name('b'), op)
            english = f'{label("a")} is {phrase} {label("b")}.'
        elif shape == 'difference':
            compatible(*(value(k).type for k in ('a', 'b', 'v')))
            p = f'{integer("a")} - {integer("b")} = {integer("v")}'
            english = f'{label("a")} minus {label("b")} equals {label("v")}.'
        elif shape == 'date_add':
            _require(value('start').type == value('due').type == _DATE and value('days').type == _NAT,
                     'date_add requires two dates and natural days')
            p = f'{integer("due")} = {integer("start")} + {integer("days")}'
            english = f'{label("due")} is {label("days")} calendar days after {label("start")}.'
        elif shape == 'within':
            _require(value('event').type == value('due').type == _DATE, 'within requires dates')
            inclusive = slots['inclusive'].value == 'true'
            p = compare(_DATE, name('event'), name('due'), '≤' if inclusive else '<')
            english = f'{label("event")} is {"on or before" if inclusive else "before"} {label("due")}.'
        elif shape in ('all', 'any', 'count', 'maximum'):
            xs = value('xs').type
            _require(isinstance(xs, ListType), f'{shape} requires a finite list')
            _require(isinstance(value('xs').value, tuple), 'Unresolved finite list')
            if shape in ('all', 'maximum'):
                _require(bool(value('xs').value), 'Applicability requires nonempty xs')
            if shape == 'maximum':
                rule, fn = predicate('f', xs.element)
                _require(value('x').type == xs.element, 'Selected member has the wrong type')
                _require(rule.result_type == value('v').type and _ordered(rule.result_type),
                         'Maximum projection/value requires identical ordered types/units')
                selected, other = f'{fn} {name("x")}', f'{fn} item'
                equality = compare(rule.result_type, selected, name('v'), '=')
                bound = compare(rule.result_type, other, selected, '≤')
                p = f'{name("x")} ∈ {name("xs")} ∧ ({equality}) ∧ (∀ item ∈ {name("xs")}, {bound})'
                english = (f'{label("x")} is a maximum-valued member of {label("xs")}, '
                           f'with {label("f")} equal to {label("v")}.')
            else:
                _, fn = predicate('p', xs.element, _BOOL)
                if shape == 'all':
                    p = f'∀ item ∈ {name("xs")}, {fn} item = true'
                    english = f'Every member of the nonempty list {label("xs")} satisfies {label("p")}.'
                elif shape == 'any':
                    p = f'∃ item ∈ {name("xs")}, {fn} item = true'
                    english = f'Some member of {label("xs")} satisfies {label("p")}.'
                else:
                    _require(value('n').type == _NAT, 'Count threshold must be nat')
                    p = f'({name("xs")}.filter {fn}).length {op} {name("n")}'
                    english = (f'The number of members of {label("xs")} satisfying {label("p")} '
                               f'is {phrase} {label("n")}.')
        elif shape == 'conflict':
            field = slots['field'].value
            fields = []
            for key in ('a', 'b'):
                type_ = value(key).type
                _require(isinstance(type_, RecordType), 'Conflict observations must be records')
                types = dict(type_.fields)
                _require({'scope', 'issuer', field} <= types.keys(), 'Missing conflict observation field')
                fields.append(types)
            _require(all(fields[0][k] == fields[1][k] for k in ('scope', 'issuer', field)),
                     'Conflict scope, issuer and field types must agree')

            def field_name(key, wire):
                lean = next(f[1] for f in type_binding(value(key).type).fields if f[0] == wire)
                return f'({name(key)}).{lean}'

            p = ' ∧ '.join(f'{field_name("a", k)} {operator} {field_name("b", k)}'
                           for k, operator in (('scope', '='), ('issuer', '≠'), (field, '≠')))
            english = f'{label("a")} and {label("b")} report different {label("field")} values for the same scope.'
        else:  # ratio: the closed registry and version check excludes any fallback theorem.
            compatible(value('a').type, value('b').type)
            _require(value('r').type == _RATIO, 'ratio requires a ratio-valued reference')
            _require(type(value('b').value) is int and value('b').value > 0,
                     'Applicability requires positive b')
            rate = value('r').value
            _require(isinstance(rate, Fraction) and rate.denominator > 0,
                     'Applicability requires positive r.denominator')
            numerator, denominator = type_binding(_RATIO).ratio_projection
            p = (f'{integer("a")} * ({denominator.format(value=name("r"))}) {op} '
                 f'{integer("b")} * ({numerator.format(value=name("r"))})')
            english = (f'With positive {label("b")}, {label("a")}/{label("b")} is {phrase} '
                       f'{rate.numerator}/{rate.denominator}.')
        q = p if claim.polarity == Polarity.POSITIVE else f'¬ ({p})'
        if claim.polarity == Polarity.NEGATIVE:
            english = 'It is not the case that: ' + english
        target = q if relation == ProofRelation.SUPPORTS else f'¬ ({q})'
        rendered = RenderedClaim(claim, relation, q, target, english, dependencies, ())
        return RenderedClaim(claim, relation, q, target, english, dependencies, _claims_file((rendered,)))
    except _NotFormalized as exc:
        return blocked(str(exc))


def generate_claims(claims: tuple[ClaimRecord, ...], facts: ResolvedFacts,
                    rules: tuple[RuleRegistration, ...], relations: Mapping[str, ProofRelation], *,
                    labels: Mapping[str, str] | None = None) -> tuple[GeneratedFile, ...]:
    """Return one deterministic Claims.lean, omitting every unsupported claim.

    ``relations`` must cover exactly the distinct claim IDs. Call render_claim
    for each claim as well when collecting not-formalized reasons for the audit.
    Empty/all-blocked batches return (). Never concatenate per-claim files: their
    paths intentionally coincide with the batch artifact's path.
    """
    ids = {c.id for c in claims}
    if len(ids) != len(claims) or ids != relations.keys():
        raise ContractError('Duplicate claim IDs or incomplete/extra proof relations')
    return _claims_file(tuple(render_claim(c, facts, rules, relations[c.id], labels=labels) for c in claims))
